// gen-ports writes the Markdown ports table from the production quadlets.
//
//	go run ./cmd/gen-ports -quadlets DIR > ports.md
package main

import (
	"flag"
	"fmt"
	"os"
	"strings"
	"time"

	"github.com/openpak/status/internal/quadlet"
)

func main() {
	dir := flag.String("quadlets", "", "directory of production *.container files")
	flag.Parse()
	if *dir == "" {
		fmt.Fprintln(os.Stderr, "usage: gen-ports -quadlets DIR")
		os.Exit(2)
	}
	units, err := quadlet.Load(*dir)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen-ports:", err)
		os.Exit(1)
	}
	fmt.Printf("# Ports\n\n_Generated by status/cmd/gen-ports from the production quadlets on %s. Do not edit by hand._\n\n", time.Now().Format("2006-01-02"))
	fmt.Print("Every service unit on the primary box, the ports it publishes and its health endpoint. Ports marked `127.0.0.1` are internal (reached through Traefik or by other services); units on the host network list the ports they serve.\n\n")
	fmt.Println("| Unit | Image | Published ports | Health | Description |")
	fmt.Println("| --- | --- | --- | --- | --- |")
	for _, u := range units {
		var ports []string
		for _, p := range u.Published {
			s := fmt.Sprintf("%d/%s", p.Host, p.Proto)
			if !p.External() {
				s = "127.0.0.1:" + s
			}
			ports = append(ports, s)
		}
		if len(ports) == 0 {
			switch {
			case len(u.Marker) > 0:
				for _, m := range u.Marker {
					ports = append(ports, fmt.Sprint(m))
				}
				ports = append(ports, "(host network)")
			case u.HostNetwork:
				ports = append(ports, "(host network)")
			default:
				ports = append(ports, "none")
			}
		}
		health := "-"
		if u.HealthPort != 0 {
			health = fmt.Sprintf("`:%d`", u.HealthPort)
		}
		fmt.Printf("| `%s` | `%s` | %s | %s | %s |\n", u.Name, u.ImageShort(), cell(strings.Join(ports, ", ")), health, cell(u.Description))
	}
}

func cell(s string) string { return strings.ReplaceAll(s, "|", "\\|") }
