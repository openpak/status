// gen-gatus appends one Gatus endpoint per production quadlet that publishes a
// port to the hand-written gatus.yaml. The generated part sits between two
// marker comments and is replaced wholesale on every run.
//
//	go run ./cmd/gen-gatus -quadlets DIR [-exclude unit,unit] [-in gatus.yaml] [-out gatus.yaml]
package main

import (
	"flag"
	"fmt"
	"os"
	"regexp"
	"sort"
	"strings"

	"github.com/openpak/status/internal/quadlet"
)

const (
	begin = "# >>> generated by cmd/gen-gatus from the production quadlets. Do not edit by hand; re-run the tool."
	end   = "# <<< end generated"
	host  = "145.241.199.19"
)

var groupOrder = []string{"Core", "Switch infra", "Switch NEX", "Switch NPLN", "Switch vendor",
	"Wii U/3DS", "Wii/DS", "PS3", "Xbox 360", "Xbox", "Infra"}

var notServices = map[string]string{
	"openpak-switch-bridge":   "loopback bridge, not a service",
	"openpak-edge":            "public TCP relay to Traefik, covered by the Console checks",
	"openpak-switch-honeypot": "handshake honeypot, no health to watch",
}

var (
	infraUnits = set("postgres", "redis", "mongo", "minio", "mailpit", "traefik", "edge", "qw-cloudflared", "turn", "connectivity")
	vendors    = set("demonware", "eos", "photon", "playfab", "klei", "shiro", "t17", "ugs", "among-us", "spelunky2",
		"battlenet", "fall-guys", "fall-guys-round", "stumble-guys", "unrailed", "astroneer", "minecraft-dungeons")
	switchInfra = set("judd", "splatnet")
	urlRe       = regexp.MustCompile(`(?m)^\s*url:\s*(\S+)`)
)

func set(s ...string) map[string]bool {
	m := map[string]bool{}
	for _, x := range s {
		m[x] = true
	}
	return m
}

func platform(u quadlet.Unit) string {
	s := u.Short
	switch {
	case strings.HasPrefix(s, "nx-"), switchInfra[s]:
		return "Switch infra"
	case strings.HasPrefix(s, "switch-"):
		return "Switch NEX"
	case strings.Contains(u.Image, "/npln:"):
		return "Switch NPLN"
	case vendors[s]:
		return "Switch vendor"
	case strings.HasPrefix(s, "nn-"), strings.Contains(u.Image, "/nex:"):
		return "Wii U/3DS"
	case strings.HasPrefix(s, "wfc-"):
		return "Wii/DS"
	case strings.HasPrefix(s, "np-"):
		return "PS3"
	case strings.HasPrefix(s, "x360-"):
		return "Xbox 360"
	case strings.HasPrefix(s, "xb-"), s == "xbl":
		return "Xbox"
	case infraUnits[s]:
		return "Infra"
	}
	return "Core"
}

type ep struct {
	group, name, url string
	others           string
}

// choose picks the port to probe: a Switch NEX title's secure port, else the
// first external TCP port, else the first external UDP port.
func choose(u quadlet.Unit) (url, label string, ok bool) {
	if strings.HasPrefix(u.Short, "switch-") && len(u.Marker) >= 2 {
		return fmt.Sprintf("tcp://%s:%d", host, u.Marker[1]), fmt.Sprintf("secure %d/tcp", u.Marker[1]), true
	}
	for _, proto := range []string{"tcp", "udp"} {
		for _, p := range u.Published {
			if p.External() && p.Proto == proto {
				return fmt.Sprintf("%s://%s:%d", proto, host, p.Host), fmt.Sprintf("%d/%s", p.Host, proto), true
			}
		}
	}
	return "", "", false
}

func main() {
	dir := flag.String("quadlets", "", "directory of production *.container files")
	in := flag.String("in", "gatus.yaml", "existing gatus.yaml")
	out := flag.String("out", "", "output file (default: same as -in)")
	exclude := flag.String("exclude", "", "comma-separated units to leave out (e.g. openpak-nx-baas)")
	flag.Parse()
	excluded := map[string]bool{}
	for _, x := range strings.Split(*exclude, ",") {
		if x = strings.TrimSpace(x); x != "" {
			excluded[strings.TrimPrefix(x, "openpak-")] = true
		}
	}
	if *dir == "" {
		fmt.Fprintln(os.Stderr, "usage: gen-gatus -quadlets DIR [-in gatus.yaml] [-out gatus.yaml]")
		os.Exit(2)
	}
	if *out == "" {
		*out = *in
	}
	b, err := os.ReadFile(*in)
	check(err)
	text := string(b)
	if i := strings.Index(text, begin); i >= 0 {
		text = text[:i]
	}
	text = strings.TrimRight(text, "\n") + "\n"

	hand := map[string]bool{}
	for _, m := range urlRe.FindAllStringSubmatch(text, -1) {
		hand[m[1]] = true
	}
	units, err := quadlet.Load(*dir)
	check(err)

	byGroup := map[string][]ep{}
	var skipped []string
	seen := map[string]bool{}
	for _, u := range units {
		if why, no := notServices[u.Name]; no {
			skipped = append(skipped, u.Short+" ("+why+")")
			continue
		}
		if excluded[u.Short] {
			skipped = append(skipped, u.Short+" (excluded with -exclude)")
			continue
		}
		url, label, ok := choose(u)
		if !ok {
			why := "no published port"
			if len(u.Published) > 0 {
				why = "only ports bound to a specific address"
			} else if u.HostNetwork {
				why = "host network, ports not declared"
			}
			skipped = append(skipped, u.Short+" ("+why+")")
			continue
		}
		if hand[url] {
			skipped = append(skipped, u.Short+" (already checked by hand: "+url+")")
			continue
		}
		g := platform(u)
		e := ep{group: g, name: u.Short + " " + label, url: url}
		if k := g + "/" + e.name; seen[k] {
			check(fmt.Errorf("duplicate endpoint %q", k))
		} else {
			seen[k] = true
		}
		byGroup[g] = append(byGroup[g], e)
	}

	var sb strings.Builder
	sb.WriteString("\n" + begin + "\n")
	sb.WriteString("# One TCP connect (or UDP dial) per unit, against the first external port; the\n")
	sb.WriteString("# Switch NEX titles are probed on their secure port. Loopback-only ports cannot\n")
	sb.WriteString("# be reached from this host and are not checked.\n")
	counts := map[string]int{}
	for _, g := range groupOrder {
		es := byGroup[g]
		if len(es) == 0 {
			continue
		}
		sort.Slice(es, func(i, j int) bool { return es[i].name < es[j].name })
		fmt.Fprintf(&sb, "\n  # ---- generated: %s ----\n", g)
		for _, e := range es {
			fmt.Fprintf(&sb, "  - name: %s\n    group: %s\n    url: %s\n    interval: 120s\n    conditions:\n      - \"[CONNECTED] == true\"\n", e.name, e.group, e.url)
			counts[g]++
		}
	}
	sort.Strings(skipped)
	sb.WriteString("\n# Not externally probeable (skipped):\n")
	for _, s := range skipped {
		sb.WriteString("#   " + s + "\n")
	}
	sb.WriteString(end + "\n")
	check(os.WriteFile(*out, []byte(text+sb.String()), 0o644))

	total := 0
	for _, g := range groupOrder {
		if counts[g] > 0 {
			fmt.Printf("%-14s %d\n", g, counts[g])
			total += counts[g]
		}
	}
	fmt.Printf("%-14s %d generated, %d skipped\n", "total", total, len(skipped))
}

func check(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen-gatus:", err)
		os.Exit(1)
	}
}
